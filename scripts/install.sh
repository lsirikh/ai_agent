#!/bin/bash
# ============================================
# EdgeVoice Installation Script
# Phase 7.3: 설치 스크립트
# ============================================
#
# Usage:
#   ./scripts/install.sh [dev|jetson]
#
# Examples:
#   ./scripts/install.sh dev      # Development environment
#   ./scripts/install.sh jetson   # Jetson deployment
# ============================================

set -e

# Colors for output
RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
BLUE='\033[0;34m'
NC='\033[0m' # No Color

# Configuration
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PROJECT_ROOT="$(dirname "$SCRIPT_DIR")"
ENV_TYPE="${1:-dev}"

# Functions
print_header() {
    echo -e "${BLUE}"
    echo "============================================"
    echo "  EdgeVoice Installation"
    echo "  Environment: $ENV_TYPE"
    echo "============================================"
    echo -e "${NC}"
}

print_step() {
    echo -e "${GREEN}[STEP]${NC} $1"
}

print_warning() {
    echo -e "${YELLOW}[WARNING]${NC} $1"
}

print_error() {
    echo -e "${RED}[ERROR]${NC} $1"
}

print_success() {
    echo -e "${GREEN}[SUCCESS]${NC} $1"
}

check_requirements() {
    print_step "Checking system requirements..."

    # Check Docker
    if ! command -v docker &> /dev/null; then
        print_error "Docker is not installed. Please install Docker first."
        echo "  - For Ubuntu: https://docs.docker.com/engine/install/ubuntu/"
        echo "  - For Jetson: https://docs.nvidia.com/jetson/jetpack/install-docker/"
        exit 1
    fi
    print_success "Docker installed: $(docker --version)"

    # Check Docker Compose
    if ! command -v docker-compose &> /dev/null && ! docker compose version &> /dev/null; then
        print_error "Docker Compose is not installed."
        exit 1
    fi
    print_success "Docker Compose installed"

    # Check NVIDIA Docker (for GPU support)
    if [ "$ENV_TYPE" = "dev" ] || [ "$ENV_TYPE" = "jetson" ]; then
        if ! docker info 2>/dev/null | grep -q "nvidia"; then
            print_warning "NVIDIA Docker runtime not detected. GPU support may not work."
            echo "  Install nvidia-docker2 for GPU support."
        else
            print_success "NVIDIA Docker runtime detected"
        fi
    fi

    # Check available disk space (minimum 20GB)
    available_space=$(df -BG "$PROJECT_ROOT" | awk 'NR==2 {print $4}' | sed 's/G//')
    if [ "$available_space" -lt 20 ]; then
        print_warning "Low disk space: ${available_space}GB available. Recommended: 20GB+"
    else
        print_success "Disk space: ${available_space}GB available"
    fi

    # Check available memory
    if [ -f /proc/meminfo ]; then
        total_mem=$(awk '/MemTotal/ {print int($2/1024/1024)}' /proc/meminfo)
        if [ "$ENV_TYPE" = "jetson" ] && [ "$total_mem" -lt 8 ]; then
            print_warning "Low memory: ${total_mem}GB. Jetson requires 8GB+ for optimal performance."
        elif [ "$ENV_TYPE" = "dev" ] && [ "$total_mem" -lt 16 ]; then
            print_warning "Low memory: ${total_mem}GB. Development requires 16GB+ for optimal performance."
        else
            print_success "Memory: ${total_mem}GB available"
        fi
    fi
}

setup_directories() {
    print_step "Setting up directories..."

    # Create required directories
    mkdir -p "$PROJECT_ROOT/models/whisper"
    mkdir -p "$PROJECT_ROOT/models/llm"
    mkdir -p "$PROJECT_ROOT/models/kokoro"
    mkdir -p "$PROJECT_ROOT/models/embedding"
    mkdir -p "$PROJECT_ROOT/models/openwakeword"
    mkdir -p "$PROJECT_ROOT/data"
    mkdir -p "$PROJECT_ROOT/logs"

    # Create log directories for each service
    for service in stt llm tts embedding wake_word rag orchestrator audio_gateway backend; do
        mkdir -p "$PROJECT_ROOT/logs/$service"
    done

    print_success "Directories created"
}

setup_environment() {
    print_step "Setting up environment..."

    # Copy .env.example to .env if not exists
    if [ ! -f "$PROJECT_ROOT/.env" ]; then
        if [ -f "$PROJECT_ROOT/.env.example" ]; then
            cp "$PROJECT_ROOT/.env.example" "$PROJECT_ROOT/.env"
            print_success "Created .env from .env.example"
            print_warning "Please edit .env file to configure your settings"
        else
            print_warning ".env.example not found. Creating default .env"
            cat > "$PROJECT_ROOT/.env" << EOF
# EdgeVoice Environment Configuration
# Generated by install.sh

# Environment type
ENVIRONMENT=$ENV_TYPE

# Model cache path
MODEL_CACHE_PATH=./models

# HuggingFace Token (required for some models)
HF_TOKEN=

# LLM Model (adjust based on your hardware)
LLM_MODEL=Qwen/Qwen2.5-7B-Instruct-GPTQ-Int4

# Log level
LOG_LEVEL=INFO
EOF
            print_success "Created default .env file"
        fi
    else
        print_success ".env file already exists"
    fi
}

download_models() {
    print_step "Checking models..."

    # Ask user if they want to download models
    read -p "Do you want to download AI models now? This may take a while. [y/N] " -n 1 -r
    echo
    if [[ $REPLY =~ ^[Yy]$ ]]; then
        if [ -f "$PROJECT_ROOT/scripts/download-models.sh" ]; then
            bash "$PROJECT_ROOT/scripts/download-models.sh" "$ENV_TYPE"
        else
            print_warning "download-models.sh not found. Please download models manually."
        fi
    else
        print_warning "Skipping model download. Run ./scripts/download-models.sh later."
    fi
}

build_images() {
    print_step "Building Docker images..."

    cd "$PROJECT_ROOT"

    if [ "$ENV_TYPE" = "jetson" ]; then
        docker-compose -f docker-compose.jetson.yml build
    else
        docker-compose -f docker-compose.dev.yml build
    fi

    print_success "Docker images built"
}

create_network() {
    print_step "Creating Docker network..."

    network_name="edgevoice-network"
    if [ "$ENV_TYPE" = "jetson" ]; then
        network_name="edgevoice-jetson-network"
    fi

    if ! docker network ls | grep -q "$network_name"; then
        docker network create "$network_name" || true
        print_success "Network $network_name created"
    else
        print_success "Network $network_name already exists"
    fi
}

print_next_steps() {
    echo ""
    echo -e "${GREEN}============================================${NC}"
    echo -e "${GREEN}  Installation Complete!${NC}"
    echo -e "${GREEN}============================================${NC}"
    echo ""
    echo "Next steps:"
    echo ""
    echo "1. Download models (if not done):"
    echo "   ./scripts/download-models.sh $ENV_TYPE"
    echo ""
    echo "2. Configure environment:"
    echo "   Edit .env file with your settings"
    echo ""
    echo "3. Start EdgeVoice:"
    if [ "$ENV_TYPE" = "jetson" ]; then
        echo "   docker-compose -f docker-compose.jetson.yml up -d"
    else
        echo "   docker-compose -f docker-compose.dev.yml up -d"
    fi
    echo ""
    echo "4. Access the dashboard:"
    echo "   http://localhost:8000"
    echo ""
    echo "5. View logs:"
    if [ "$ENV_TYPE" = "jetson" ]; then
        echo "   docker-compose -f docker-compose.jetson.yml logs -f"
    else
        echo "   docker-compose -f docker-compose.dev.yml logs -f"
    fi
    echo ""
    echo "For more information, see README.md"
}

# Main execution
main() {
    print_header

    # Validate environment type
    if [ "$ENV_TYPE" != "dev" ] && [ "$ENV_TYPE" != "jetson" ]; then
        print_error "Invalid environment type: $ENV_TYPE"
        echo "Usage: $0 [dev|jetson]"
        exit 1
    fi

    check_requirements
    setup_directories
    setup_environment
    download_models
    build_images
    create_network
    print_next_steps
}

main "$@"
